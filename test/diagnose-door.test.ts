// ---------------------------------------------------------------------------
// Fixtures: a two-door host shaped like the field provider (desktop-60026li):
// ukp-door uses the template's literal %USERPROFILE% argument, the renamed
// second door an absolute path; plus noise tasks that must NOT match.
// ---------------------------------------------------------------------------

const HOME = "C:\\Users\\fixture";

const VBS_MAIN = `${HOME}\\.ukp\\start-door-hidden.vbs`;
const CMD_MAIN = `${HOME}\\.ukp\\start-door.cmd`;
const LOG_MAIN = `${HOME}\\.ukp\\door.log`;
const VBS_SECOND = `${HOME}\\.ukp\\start-agent-eval-hidden.vbs`;
const CMD_SECOND = `${HOME}\\.ukp\\start-agent-eval.cmd`;
const LOG_SECOND = `${HOME}\\.ukp\\door-agent-eval.log`;

const SECRET = "tok-do-not-print-0123456789abcdef";

const CMD_MAIN_TEXT = [
  "@echo off",
  "rem UKP resident door (generated by ukp serve --print-task)",
  `set "UKP_SERVE_TOKEN=${SECRET}"`,
  `   ukp serve --endpoint skill-dev --host 0.0.0.0 --port 8570 --tls`,
].join("\r\n");

const VBS_MAIN_TEXT = [
  "' UKP door hidden launcher",
  "Dim cmdline : cmdline = \"cmd /c \" & q & q & home & \"\\.ukp\\start-door.cmd\" & q & \" >> \" & q & home & \"\\.ukp\\door.log\" & q & \" 2>&1\" & q",
].join("\r\n");

const LOG_MAIN_TEXT = [
  "serving endpoint 'skill-dev' (ukp-remote v1)",
  "  listening: https://0.0.0.0:8570",
  "  auth: bearer token required",
  "  tls: self-signed identity (persisted) sha256/EXAMPLE (SAN: DNS:localhost)",
].join("\r\n");

const CMD_SECOND_TEXT = [
  "@echo off",
  `set "UKP_SERVE_TOKEN=${SECRET}"`,
  `ukp serve --endpoint agent-eval --host 0.0.0.0 --port 8571 --tls`,
].join("\r\n");

const VBS_SECOND_TEXT = VBS_MAIN_TEXT
  .replaceAll("start-door.cmd", "start-agent-eval.cmd")
  .replaceAll("\\.ukp\\door.log", "\\.ukp\\door-agent-eval.log");

const LOG_SECOND_TEXT = [
  "serving endpoint 'agent-eval' (ukp-remote v1)",
  "  listening: https://0.0.0.0:8571",
  "  tls: self-signed identity (generated) sha256/EXAMPLE2 (SAN: DNS:localhost)",
].join("\r\n");

function baseFiles(): Map<string, string> {
  return new Map<string, string>([
    [VBS_MAIN, VBS_MAIN_TEXT],
    [CMD_MAIN, CMD_MAIN_TEXT],
    [LOG_MAIN, LOG_MAIN_TEXT],
    [VBS_SECOND, VBS_SECOND_TEXT],
    [CMD_SECOND, CMD_SECOND_TEXT],
    [LOG_SECOND, LOG_SECOND_TEXT],
  ]);
}

